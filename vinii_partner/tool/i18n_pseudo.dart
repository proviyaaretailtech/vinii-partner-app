String generate(String arbSource) {
  final arb = jsonDecode(arbSource) as Map<String, dynamic>;
  final buf = StringBuffer()
    ..writeln('// GENERATED by `dart run tool/i18n_pseudo.dart` from')
    ..writeln('// lib/l10n/app_en.arb. Do not edit by hand.')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln('// dart format off')
    ..writeln()
    ..writeln("import 'package:flutter/foundation.dart';")
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln()
    ..writeln("import 'app_localizations.dart';")
    ..writeln("import 'app_localizations_en.dart';")
    ..writeln()
    ..writeln(
      '/// English, accented and ~30% longer, in [ ]. See tool/i18n_pseudo.dart.',
    )
    ..writeln('class PseudoLocalizations extends AppLocalizationsEn {')
    ..writeln('  static String _p(String s) {')
    ..writeln("    final b = StringBuffer('[');")
    ..writeln('    for (final rune in s.runes) {')
    ..writeln('      final ch = String.fromCharCode(rune);')
    ..writeln('      final a = _accents[ch] ?? ch;')
    ..writeln('      b.write(a);')
    ..writeln("      if ('aeiouAEIOU'.contains(ch)) b.write(a);")
    ..writeln('    }')
    ..writeln("    b.write(']');")
    ..writeln('    return b.toString();')
    ..writeln('  }')
    ..writeln()
    ..writeln('  static const _accents = <String, String>{');
  _accents.forEach((k, v) => buf.writeln("    '$k': '$v',"));
  buf
    ..writeln('  };')
    ..writeln();

  final keys = arb.keys.where((k) => !k.startsWith('@')).toList();
  for (final key in keys) {
    final meta = arb['@$key'] as Map<String, dynamic>?;
    final placeholders =
        (meta?['placeholders'] as Map<String, dynamic>?) ??
        const <String, dynamic>{};
    buf.writeln('  @override');
    if (placeholders.isEmpty) {
      buf.writeln('  String get $key => _p(super.$key);');
    } else {
      final params = [
        for (final e in placeholders.entries)
          'required ${(e.value as Map)['type'] ?? 'String'} ${e.key}',
      ].join(', ');
      final passes = [for (final n in placeholders.keys) '$n: $n'].join(', ');
      buf.writeln('  String $key({$params}) => _p(super.$key($passes));');
    }
  }
  buf
    ..writeln('}')
    ..writeln()
    ..writeln(
      '/// Mounted only when the app is built with PSEUDO_LOCALE=true; listed '
      'before the real',
    )
    ..writeln('/// delegate so `en_XA` finds it first.')
    ..writeln(
      'class PseudoLocalizationsDelegate extends '
      'LocalizationsDelegate<AppLocalizations> {',
    )
    ..writeln('  const PseudoLocalizationsDelegate();')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  bool isSupported(Locale locale) =>')
    ..writeln(
      "      locale.languageCode == 'en' && locale.countryCode == 'XA';",
    )
    ..writeln()
    ..writeln('  @override')
    ..writeln('  Future<AppLocalizations> load(Locale locale) =>')
    ..writeln(
      '      SynchronousFuture<AppLocalizations>(PseudoLocalizations());',
    )
    ..writeln()
    ..writeln('  @override')
    ..writeln('  bool shouldReload(PseudoLocalizationsDelegate old) => false;')
    ..writeln('}');
  return buf.toString();
}
