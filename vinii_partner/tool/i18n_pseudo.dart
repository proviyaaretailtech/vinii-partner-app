// Generates lib/l10n/pseudo_localizations.dart: a fake "pseudo" language that
// shows every catalogue string accented, ~30% longer and wrapped in [ ].
//
//   dart run tool/i18n_pseudo.dart           regenerate the file
//   dart run tool/i18n_pseudo.dart --check   exit 1 when it is out of date
//
// Run the app with `--dart-define=PSEUDO_LOCALE=true`: the language screen
// gets a "Pseudo (test)" tile (and the app starts in it). Text that is still
// plain English is hard-coded; a screen that overflows would overflow in
// Hindi too. The class is compiled out of release builds, because the flag
// that mounts it is a compile-time constant.
import 'dart:convert';
import 'dart:io';

const _arb = 'lib/l10n/app_en.arb';
const _out = 'lib/l10n/pseudo_localizations.dart';

void main(List<String> args) {
  final check = args.contains('--check');
  final source = generate(File(_arb).readAsStringSync());
  final out = File(_out);
  if (check) {
    final current = out.existsSync() ? out.readAsStringSync() : '';
    if (current != source) {
      stderr.writeln(
        '$_out is out of date: run `dart run tool/i18n_pseudo.dart`.',
      );
      exit(1);
    }
    stdout.writeln('$_out is up to date.');
    return;
  }
  out.writeAsStringSync(source);
  stdout.writeln('Wrote $_out');
}

